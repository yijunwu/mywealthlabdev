                base.m_string = str + "><v:stroke dashstyle=\"" + this.PenStyle(base.Pen) + "\"" + this.PenWidth(base.Pen, "weight") + "/></v:" + element + ">";
            }
            else
            {
                base.m_string = base.m_string + this.PenWidth(base.Pen, "strokeweight") + "/>";
            }
            return base.m_string;
