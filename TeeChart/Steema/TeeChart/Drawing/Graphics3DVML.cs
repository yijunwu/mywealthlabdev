                base.m_string = str3 + r.Left.ToString() + ";top:" + r.Top.ToString() + ";width:";
                int num = r.Width - 1;
                base.m_string = base.m_string + num.ToString() + ";height:";
                base.m_string = base.m_string + ((r.Height - 1)).ToString() + "\"";
                if (b.Visible)
                {
                    base.m_string = base.m_string + " fillcolor=" + this.VMLColor(b.Color, false);
                }
                else
                {
                    base.m_string = base.m_string + " filled=\"false\"";
                }
                if (UsePen && base.Pen.Visible)
                {
                    base.m_string = base.m_string + " strokecolor=" + this.VMLColor(base.Pen.Color, false);
                }
                else
                {
                    base.m_string = base.m_string + " stroked=\"f\"";
                }
                float num2 = 1f - (b.Transparency * 0.01f);
                if (num2 < 1f)
                {
                    string str2 = num2.ToString().Replace(',', '.');
                    base.m_string = base.m_string + " opacity=\"" + str2 + "\"";
                }
                base.m_string = base.m_string + this.VMLPen(element);
                this.AddToStream(base.m_string);
