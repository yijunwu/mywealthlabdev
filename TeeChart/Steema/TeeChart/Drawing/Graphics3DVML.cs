        protected override void DoText(int x, int y, string text, double degAngle, Color c)
        {
            float num = 0f;
            if (base.TextAlign == StringAlignment.Center)
            {
                num = this.TextWidth(text) * 0.5f;
            }
            else if (base.TextAlign == StringAlignment.Far)
            {
                num = this.TextWidth(text);
            }
            x -= Utils.Round(num);
            if (degAngle == 0.0)
            {
                base.m_string = "<v:textbox style=\"position:absolute; left:" + x.ToString() + "; top:" + y.ToString();
                base.m_string = base.m_string + "; color:" + this.VMLColor(c, true) + "; text-align:left; ";
                base.m_string = base.m_string + this.FontProperties(base.Font) + "\">";
                base.m_string = base.m_string + text;
                base.m_string = base.m_string + "</v:textbox>";
            }
            else
            {
                num = this.TextWidth(text);
                float num6 = this.TextHeight(text);
                double d = (degAngle * 3.1415926535897931) / 180.0;
                double num8 = Math.Cos(d);
                double num9 = Math.Sin(d);
                y += Utils.Round((double) (num6 * 0.5));
                int num2 = Utils.Round((double) (x + (num9 * num6)));
                int num3 = Utils.Round((double) (y + (num8 * num6)));
                int num4 = Utils.Round((double) (x + ((num8 * num) + (num9 * num6))));
                int num5 = Utils.Round((double) (y + ((-num9 * num) + (num8 * num6))));
                if (num2 == num4)
                {
                    num4++;
                }
                if (num3 == num5)
                {
                    num5++;
                }
                if ((degAngle > 90.0) && (degAngle < 270.0))
                {
                    num2 -= Utils.Round((double) ((num * num8) + (num6 * num9)));
                    num4 -= Utils.Round((double) ((num * num8) + (num6 * num9)));
                }
                base.m_string = "<v:line from=\"" + num2.ToString() + "," + num3.ToString() + "\" to=\"";
                string str = base.m_string;
                base.m_string = str + num4.ToString() + "," + num5.ToString() + "\" style=\"position: absolute\">\r\n";
                base.m_string = base.m_string + "  <v:fill on=\"True\" color=" + this.VMLColor(c, false) + "/>\r\n";
                base.m_string = base.m_string + "  <v:path textpathok=\"True\"/>\r\n";
                base.m_string = base.m_string + "  <v:textpath on=\"True\" trim=\"True\" string=\"" + text + "\"";
                base.m_string = base.m_string + "; style=\"font: ";
                if (base.Font.Italic)
                {
                    base.m_string = base.m_string + "italic normal ";
                }
                else
                {
                    base.m_string = base.m_string + "normal normal ";
                }
                if (base.Font.Bold)
                {
                    base.m_string = base.m_string + "bold ";
                }
                else
                {
                    base.m_string = base.m_string + "normal ";
                }
                base.m_string = base.m_string + base.Font.Size.ToString() + "pt " + base.Font.Name;
                base.m_string = base.m_string + "\"/>\r\n";
                base.m_string = base.m_string + "</v:line>";
            }
            this.AddToStream(base.m_string);
        }

